#!/usr/bin/env python3
"""Embed the repository's Lucide alpha4 assets for the C6 reusable cards.

Source/provenance: assets/round-1.32/icons/*.a4, produced by the upstream
Lucide icon asset pipeline. Each 96x96 mask is box-filtered to 32x32; the
4-bit coverage and LVGL's high-nibble-first pixel order are preserved.
No third-party image library or runtime file access is required.
"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/round-1.32/icons"
OUTPUT = ROOT / "firmware/targets/c6-lcd-1.47/main/generated/c6_ui_icons.h"


def reduce_alpha4(data):
    if len(data) != 96 * 96 // 2:
        raise ValueError("expected a 96x96 alpha4 mask")
    def pixel(x, y):
        index = y * 96 + x
        return (data[index // 2] >> (4 if index % 2 == 0 else 0)) & 15
    pixels = []
    for y in range(32):
        for x in range(32):
            pixels.append((sum(pixel(x*3+dx, y*3+dy)
                               for dy in range(3) for dx in range(3)) + 4) // 9)
    return bytes((pixels[i] << 4) | pixels[i+1] for i in range(0, len(pixels), 2))


def generate(source=SOURCE):
    lines = ["/* Generated by tools/c6_ui_icons.py. Do not edit by hand.",
             " * Original Lucide masks: .a4 files in assets/round-1.32/icons/.",
             " * 96x96 alpha4 -> 32x32 alpha4, rounded 3x3 box coverage.",
             " * See firmware/NOTICE for the original ISC/MIT licenses.",
             " */", "#pragma once", "#include <stdint.h>", "#include <string.h>",
             "#include <lvgl.h>", ""]
    names = []
    for path in sorted(source.glob("*.a4")):
        name = path.stem.replace("-", "_")
        data = reduce_alpha4(path.read_bytes())
        lines.append(f"static const uint8_t c6_icon_{name}_pixels[512] = {{")
        for start in range(0, len(data), 24):
            lines.append("    " + ",".join(f"0x{v:02x}" for v in data[start:start+24]) + ",")
        lines.extend(["};", f"static const lv_img_dsc_t c6_icon_{name} = {{",
                      "    .header = {.always_zero=0, .w=32, .h=32, .cf=LV_IMG_CF_ALPHA_4BIT},",
                      f"    .data_size=512, .data=c6_icon_{name}_pixels,", "};"])
        names.append((path.name, name))
    if not names:
        raise ValueError("no icon masks found")
    lines.extend(["", "static const lv_img_dsc_t *c6_ui_icon_image(const char *path) {",
                  "    if (!path) return NULL;",
                  "    const char *base = strrchr(path, '/');",
                  "    base = base ? base + 1 : path;"])
    for filename, name in names:
        lines.append(f'    if (strcmp(base, "{filename}") == 0) return &c6_icon_{name};')
    lines.extend(["    return NULL;", "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify checked-in output")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            parser.exit(1, "C6 icon header needs regeneration\n")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content)
    print(f"{len(list(SOURCE.glob('*.a4')))} icons; {len(list(SOURCE.glob('*.a4'))) * 512} alpha bytes")


if __name__ == "__main__":
    main()
